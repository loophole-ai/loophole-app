# Exports the Loophole customization delta (upstream -> HEAD) into:
#   patches/*.patch   text-only patches, grouped by topic, ordered by patches/series
#   assets/           binary overlay (icons, logos) copied over the tree at apply time
#   assets/deletes.txt files that must be removed from the upstream tree
#
# Everything is derived from COMMITTED state: UPSTREAM-REF vs HEAD.
# Uncommitted changes are deliberately ignored (the script aborts if binaries differ).
#
# Run this after every upstream sync or after committing new Loophole changes.

#Requires -Version 5.1
param(
    [string]$UpstreamRef
)

$ErrorActionPreference = "Stop"
$repoRoot = (Resolve-Path "$PSScriptRoot\..\..").Path
Set-Location $repoRoot

if (-not $UpstreamRef) {
    $UpstreamRef = (Get-Content (Join-Path $repoRoot "UPSTREAM-REF") -Raw).Trim()
}
if (-not $UpstreamRef) { throw "UPSTREAM-REF file is empty." }

# --- sanity checks -----------------------------------------------------------

git merge-base --is-ancestor $UpstreamRef HEAD 2>$null
if ($LASTEXITCODE -ne 0) {
    throw "UPSTREAM-REF ($UpstreamRef) is not an ancestor of HEAD. Sync upstream first, then update UPSTREAM-REF."
}

$dirty = git status --porcelain
if ($dirty) {
    Write-Warning "Working tree has uncommitted changes (they will NOT be exported):"
    $dirty | ForEach-Object { Write-Warning "  $_" }
}

# --- classify changed files --------------------------------------------------

# exclude the patch system's own files (they exist in HEAD, not upstream) and bun.lock
$selfExcludeArgs = @(
    ":(exclude)patches"
    ":(exclude)assets"
    ":(exclude)scripts"
    ":(exclude)UPSTREAM-REF"
    ":(exclude)PATCHES.md"
    ":(exclude)bun.lock"
)

$all = @(git -c core.quotepath=false diff --name-only --no-renames $UpstreamRef HEAD -- . @selfExcludeArgs)
if (-not $all) { throw "No differences between $UpstreamRef and HEAD." }

# binaries (from numstat: "- - path")
$binaries = @()    # still present in HEAD -> assets overlay
$binDeletes = @()  # deleted vs upstream  -> assets/deletes.txt
foreach ($line in (git -c core.quotepath=false diff --numstat --no-renames $UpstreamRef HEAD -- . @selfExcludeArgs)) {
    $parts = $line -split "`t"
    if ($parts.Count -ge 3 -and $parts[0] -eq "-" -and $parts[1] -eq "-") {
        $p = $parts[2]
        $exists = git -c core.quotepath=false ls-tree --name-only HEAD -- $p
        if ($exists) { $binaries += $p } else { $binDeletes += $p }
    }
}

# --- patch groups (path-based; group 1 is the catch-all) ----------------------

$licensingDocs = @(
    "LICENSE"
    "LICENSE-opencode.md"
    "NOTICE.md"
    "README.md"
    "SECURITY.md"
    "CONTRIBUTING.md"
    "STATS.md"
    ".github/workflows/stats.yml"
    "script/stats.ts"
    "packages/cli/package.json"
    "packages/cli/script/build.ts"
    "packages/cli/script/publish.ts"
) + @($all | Where-Object { $_ -like "README.*.md" })

$desktopChannels = @(
    "packages/desktop/package.json"
    "packages/desktop/electron-builder.config.ts"
    "packages/app/src/shell/commands/desktop-menu.ts"
)

$alwaysExcluded = @("bun.lock")  # lockfile is regenerated by `bun install` after patching

$rebrandCore = @($all | Where-Object {
    $licensingDocs -notcontains $_ -and
    $desktopChannels -notcontains $_ -and
    $alwaysExcluded -notcontains $_
})

$groups = [ordered]@{
    "0001-rebrand-core"     = $rebrandCore
    "0002-licensing-docs"   = $licensingDocs
    "0003-desktop-channels" = $desktopChannels
}

# --- guard: binaries must match HEAD before copying from the worktree --------

$dirtyPaths = @($dirty | ForEach-Object { $_.Substring(3).Trim() })
foreach ($b in $binaries) {
    if ($dirtyPaths -contains $b) {
        throw "Binary '$b' has uncommitted changes. Commit first, then re-run the export."
    }
}

# --- write patches ------------------------------------------------------------

function Write-Patch([string]$name, [string[]]$files) {
    $textFiles = @($files | Where-Object { $binaries -notcontains $_ -and $binDeletes -notcontains $_ })
    $patchPath = Join-Path $repoRoot "patches\$name.patch"
    if ($textFiles.Count -eq 0) {
        if (Test-Path $patchPath) { Remove-Item $patchPath }
        return $false
    }
    $pathArgs = ($textFiles | ForEach-Object { "`"$_`"" }) -join " "
    $cmd = "git -c core.quotepath=false diff --no-color --no-renames $UpstreamRef HEAD -- $pathArgs > `"$patchPath`""
    cmd /c $cmd
    if ($LASTEXITCODE -ne 0) { throw "git diff failed for group $name" }
    return $true
}

$written = @()
foreach ($entry in $groups.GetEnumerator()) {
    if (Write-Patch $entry.Key $entry.Value) { $written += "$($entry.Key).patch" }
}

# series file reflects what was actually written
$written | Set-Content -Encoding ascii (Join-Path $repoRoot "patches\series")

# --- write assets overlay ------------------------------------------------------

$assetsDir = Join-Path $repoRoot "assets"
if (Test-Path $assetsDir) { Remove-Item $assetsDir -Recurse -Force }
New-Item -ItemType Directory -Path $assetsDir | Out-Null

foreach ($b in $binaries) {
    $src = Join-Path $repoRoot ($b -replace "/", "\")
    $dst = Join-Path $assetsDir ($b -replace "/", "\")
    $dstDir = Split-Path $dst -Parent
    if (-not (Test-Path $dstDir)) { New-Item -ItemType Directory -Path $dstDir -Force | Out-Null }
    Copy-Item $src $dst -Force
}

$deletesPath = Join-Path $assetsDir "deletes.txt"
if ($binDeletes.Count -gt 0) {
    $binDeletes | Set-Content -Encoding ascii $deletesPath
} elseif (Test-Path $deletesPath) {
    Remove-Item $deletesPath
}

# --- summary -------------------------------------------------------------------

$totalLines = 0
foreach ($p in $written) {
    $lines = (Get-Content (Join-Path $repoRoot "patches\$p") | Measure-Object -Line).Lines
    $totalLines += $lines
    Write-Host ("  {0,-28} {1,6} lines" -f $p, $lines)
}
Write-Host ""
Write-Host ("Binaries copied to assets/: {0}" -f $binaries.Count)
if ($binDeletes.Count -gt 0) {
    Write-Host ("Deletions listed in assets/deletes.txt: {0}" -f $binDeletes.Count)
}
Write-Host ("Patches based on upstream: {0}" -f $UpstreamRef)
Write-Host "Done."
